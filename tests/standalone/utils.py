"""Helpers shared by the standalone tests."""

from pathlib import Path
from typing import List
import re


# ── BabyJubjub, the default twisted-Edwards curve of this app ─────────
#
# a*x^2 + y^2 = 1 + d*x^2*y^2  over  F_p
#
# The constants mirror src/zknox/src/ecc/zkn_tEdwards.c (bbjj_prime,
# bbjj_A, bbjj_D). They are duplicated here on purpose: a test that read
# them from the same source it is checking would confirm nothing.

BBJJ_P = 21888242871839275222246405745257275088548364400416034343698204186575808495617
BBJJ_A = 168700
BBJJ_D = 168696
# Order of the prime-order subgroup generated by Base8.
BBJJ_L = 2736030358979909402780800718157159386076813972158567259200215660948447373041


def is_on_babyjubjub(x: int, y: int) -> bool:
    """Curve-equation membership. Says nothing about the subgroup."""
    if not (0 <= x < BBJJ_P and 0 <= y < BBJJ_P):
        return False
    lhs = (BBJJ_A * x * x + y * y) % BBJJ_P
    rhs = (1 + BBJJ_D * x * x * y * y) % BBJJ_P
    return lhs == rhs


def check_point_bytes(point: bytes) -> None:
    """Assert that a 64-byte x||y big-endian encoding is a curve point."""
    assert len(point) == 64, f"expected 64 bytes, got {len(point)}"
    x = int.from_bytes(point[0:32], "big")
    y = int.from_bytes(point[32:64], "big")
    assert is_on_babyjubjub(x, y), \
        f"point off the curve: x={x:#x} y={y:#x}"


# ── Makefile introspection ────────────────────────────────────────────

def verify_name(name: str) -> None:
    """Verify the app name against APPNAME in the Makefile."""
    name_str = ""
    name_re = re.compile(r"^APPNAME\s?=\s?\"?(?P<val>\w+)\"?", re.I)
    for line in _read_makefile():
        info = name_re.match(line)
        if info:
            name_str = info.groupdict()["val"]
    assert name == name_str


def verify_version(version: str) -> None:
    """Verify the app version against APPVERSION_* in the Makefile."""
    vers_dict = {}
    version_re = re.compile(r"^APPVERSION_(?P<part>\w)\s?=\s?(?P<val>\d*)", re.I)
    for line in _read_makefile():
        info = version_re.match(line)
        if info:
            dinfo = info.groupdict()
            vers_dict[dinfo["part"]] = dinfo["val"]
    vers_str = f"{vers_dict['M']}.{vers_dict['N']}.{vers_dict['P']}"
    assert version == vers_str


def makefile_version() -> tuple:
    """(major, minor, patch) as ints, read from the Makefile."""
    vers_dict = {}
    version_re = re.compile(r"^APPVERSION_(?P<part>\w)\s?=\s?(?P<val>\d*)", re.I)
    for line in _read_makefile():
        info = version_re.match(line)
        if info:
            dinfo = info.groupdict()
            vers_dict[dinfo["part"]] = int(dinfo["val"])
    return (vers_dict["M"], vers_dict["N"], vers_dict["P"])


def _read_makefile() -> List[str]:
    """Read lines from the repo-root Makefile."""
    parent = Path(__file__).parent.parent.parent.resolve()
    with open(f"{parent}/Makefile", "r", encoding="utf-8") as f_p:
        return f_p.readlines()
